test("thin: KEYBOARD map panning (arrow keys) does NOT activate the simplification", async () => {
  // Leaflet's keyboard pan is a `move`/`moveend` sequence with no `dragstart` —
  // it must stay fully unaffected by a mouse-drag-only optimization, so keyboard
  // and screen-reader users never see clusters disappear.
  const page = await newPage();
  try {
    await page.evaluate(() => document.getElementById("map").focus());
    await page.keyboard.down("ArrowRight");
    await page.waitForTimeout(150);
    const duringKeyboardPan = await thinActive(page);
    await page.keyboard.up("ArrowRight");
    await page.waitForTimeout(150);
    assert.equal(duringKeyboardPan, false, "keyboard map pan must not thin");
    assert.ok((await visibleClusterCount(page)) > 0, "clusters stay visible on keyboard pan");
  } finally { await close(page); }
});

test("thin: reduced-motion preference suppresses the reappearance fade", async () => {
  const page = await newPage();
  try {
    await page.emulateMedia({ reducedMotion: "reduce" });
    const matches = await page.evaluate(() => window.matchMedia("(prefers-reduced-motion: reduce)").matches);
    assert.equal(matches, true, "test harness honours the reduced-motion emulation");
    const animationNone = await page.evaluate(() => {
      const probe = document.querySelector(".poi-cluster-icon");
      probe.classList.add("k12-reappear");
      const name = getComputedStyle(probe).animationName;
      probe.classList.remove("k12-reappear");
      return name;
    });
    assert.equal(animationNone, "none", "the k12ClusterFade animation is suppressed under prefers-reduced-motion");
  } finally { await close(page); }
});

test("thin: a FOCUSED cluster icon is NOT hidden while thinned (keyboard/SR safety)", async () => {
  // A mouse drag blurs the focused element on pointer-down, so the keyboard/SR
  // concern is the CSS contract itself: while the map carries k12-panning, the
  // rule `.poi-cluster-icon:not(:focus){display:none}` must hide the others but
  // never the focused one (a focused node must not become display:none). Assert
  // that mechanism directly — it is independent of how the class is applied, and
  // the mouse-drag activation path is covered by the other tests.
  const page = await newPage();
  try {
    const result = await page.evaluate(() => {
      const icons = [...document.querySelectorAll(".poi-cluster-icon")];
      if (icons.length < 2) return { ok: false, reason: `need >=2 clusters, had ${icons.length}` };
      const focusEl = icons[0];
      focusEl.focus();
      const focusedActive = document.activeElement === focusEl;
      // apply the thinned state the way dragstart would
      const map = document.getElementById("map");
      map.classList.add("k12-panning");
      const focusedDisplay = getComputedStyle(focusEl).display;
      const otherHidden = getComputedStyle(icons[1]).display === "none";
      map.classList.remove("k12-panning"); // restore
      return { ok: true, focusedActive, focusedDisplay, otherHidden };
    });
    assert.ok(result.ok, `clusters present: ${result.reason || ""}`);
    assert.equal(result.focusedActive, true, "a cluster icon can take focus");
    assert.notEqual(result.focusedDisplay, "none", "the focused cluster is NOT hidden while thinned");
    assert.equal(result.otherHidden, true, "a non-focused cluster IS hidden while thinned");
  } finally { await close(page); }
});

test("thin: works in ES and on the satellite basemap; geometry/labels untouched", async () => {
  const page = await newPage();
  try {
    await page.evaluate(() => { const s = document.getElementById("languageSelect"); if (s) { s.value = "es"; s.dispatchEvent(new Event("change", { bubbles: true })); } });
    await page.evaluate(() => { const s = document.getElementById("basemapSelect"); if (s) { s.value = "satellite"; s.dispatchEvent(new Event("change", { bubbles: true })); } });
    await page.waitForTimeout(200);
    const p = await mapDragPoint(page);
    await page.mouse.move(p.x, p.y); await page.mouse.down();
    await page.mouse.move(p.x + 80, p.y + 50, { steps: 4 });
    assert.equal(await thinActive(page), true, "thin activates on satellite + ES");
    assert.equal(await visibleClusterCount(page), 0, "clusters hidden during drag (satellite+ES)");
    await page.mouse.up();
    await page.waitForFunction(() => window.__K12_THIN__.active() === false);
    assert.ok((await visibleClusterCount(page)) > 5, "clusters restored (satellite+ES)");
  } finally { await close(page); }
});

test("thin: visual before/during/after capture (popping/reinstatement review)", async () => {
  const os = await import("node:os");
  const dir = path.join(os.tmpdir(), "k12-thin-visuals");
  fs.mkdirSync(dir, { recursive: true });
  for (const [label, vp] of [["desktop", { width: 1200, height: 860 }], ["tablet", { width: 834, height: 1112 }]]) {
    const page = await newPage();
    await page.setViewportSize(vp);
    await page.waitForFunction(() => document.querySelectorAll(".poi-cluster-icon").length > 5);
    const map = page.locator("#map");
    await map.screenshot({ path: path.join(dir, `${label}_1_before.png`) });
    const b = await page.evaluate(() => { const m = document.getElementById("map").getBoundingClientRect(); return { x: m.left, y: m.top, w: m.width, h: m.height }; });
    await page.mouse.move(b.x + b.w * 0.25, b.y + b.h * 0.3); await page.mouse.down();
    await page.mouse.move(b.x + b.w * 0.45, b.y + b.h * 0.5, { steps: 6 });
    await page.waitForTimeout(120);
    await map.screenshot({ path: path.join(dir, `${label}_2_during.png`) });
    await page.mouse.up();
    await page.waitForTimeout(400);
    await map.screenshot({ path: path.join(dir, `${label}_3_after.png`) });
    await close(page);
  }
  console.log(`[k12-thin] visuals written to ${dir}`);
  assert.ok(fs.existsSync(path.join(dir, "desktop_2_during.png")));
});

