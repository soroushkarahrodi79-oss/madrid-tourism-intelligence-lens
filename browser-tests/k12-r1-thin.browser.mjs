// K12-R1 (#97 / reviews 5571780753, 5572587267) — acceptance contract for the
// gated `thin` pan optimization (?k12opt=thin, loopback host only). It defends
// the UX/a11y requirements the reviews asked for BEFORE `thin` could ever
// become a default:
//   * it activates ONLY for a user-initiated MAP DRAG (not zoom, not programmatic
//     camera moves, not a marker drag, not keyboard panning);
//   * it restores the POI cluster icons on EVERY termination path exercised here
//     (dragend/moveend via the drag test, blur, pointercancel, touchcancel,
//     visibilitychange) — the map is never left thinned;
//   * cluster DOM identity/content/placement is restored EXACTLY (same
//     {screen-pos:count-text} signature, not just a count) once the view is
//     put back to where it was before the drag;
//   * a FOCUSED cluster is never hidden (keyboard/screen-reader safety), and the
//     reappearance fade is suppressed under prefers-reduced-motion;
//   * it works in ES and EN and on both basemaps.
// Not covered here (synthetic/dispatched events only, no real touch hardware):
// native touch-driven drag and pinch-zoom gestures. Leaflet's own touch/pinch
// handling is independent of the dragstart-gated `thin` listener and out of
// scope for this bounded test-only increment; a physical-device pass remains
// the AC-P0-12 release gate regardless.
// Nothing here changes scientific geometry, HATI or AC-P0-12 thresholds.

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MIME = {
  ".css": "text/css; charset=utf-8", ".geojson": "application/geo+json; charset=utf-8",
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8", ".png": "image/png", ".svg": "image/svg+xml",
};

// The production POI density comes from data/runtime_poi.json, a deploy-time
// artifact generated by GitHub Actions and git-ignored — so it is ABSENT on a
// fresh CI checkout (the app then falls back to the tiny committed snapshot and
// renders almost no clusters). To make these tests deterministic and independent
// of that artifact on every platform, the page route below fulfils the
// runtime_poi request with a synthetic dense `bike` layer (a DENSE_LAYER_TYPE):
// 10 groups of 3 points, each group spaced > one 60px cell apart at zoom 14 and
// each group's points within a single cell, so clusterPointsByPixelGrid yields
// 10 `.poi-cluster-icon` markers (count 3) at zoom 14. No analytical meaning —
// purely a rendering fixture for the `thin` acceptance contract.
const RUNTIME_POI_FIXTURE = JSON.stringify((() => {
  const bike = [];
  for (let i = 0; i < 5; i++) {
    for (let j = 0; j < 2; j++) {
      const lat = 40.4 + j * 0.008; // > ~0.0039° (60px) apart vertically
      const lon = -3.72 + i * 0.01; // > ~0.00515° (60px) apart horizontally
      for (let k = 0; k < 3; k++) {
        // three points within the same 60px cell → a cluster of count 3
        bike.push({ id: `fix-${i}-${j}-${k}`, name: `Fixture ${i}${j}${k}`, lat: lat + k * 0.0006, lon: lon + k * 0.0006 });
      }
    }
  }
  return { layers: { bike } };
})());

const server = http.createServer((request, response) => {
  const pathname = decodeURIComponent(new URL(request.url, "http://127.0.0.1").pathname);
  const relative = pathname === "/" ? "index.html" : pathname.slice(1);
  const target = path.resolve(ROOT, relative);
  if (!target.startsWith(`${ROOT}${path.sep}`) && target !== path.join(ROOT, "index.html")) {
    response.writeHead(403).end("Forbidden"); return;
  }
  fs.readFile(target, (error, content) => {
    if (error) { response.writeHead(404).end("Not found"); return; }
    response.writeHead(200, { "content-type": MIME[path.extname(target)] || "application/octet-stream" });
    response.end(content);
  });
});
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
const { port } = server.address();
const browser = await chromium.launch({ headless: true });

async function newPage() {
  const context = await browser.newContext({ viewport: { width: 1200, height: 860 } });
  const page = await context.newPage();
  // Headless Linux CI boots the full POI layer noticeably slower than a warm local
  // run, so use the same generous readiness budget the measurement harness proves
  // reliable (60s), not a tight 20s.
  page.setDefaultTimeout(60000);
  const pageErrors = [];
  page.on("pageerror", (e) => pageErrors.push(String(e)));
  page.on("console", (m) => { if (m.type() === "error") pageErrors.push(m.text()); });
  await page.route("**/*", (route) => {
    const url = new URL(route.request().url());
    if (url.hostname !== "127.0.0.1" && url.hostname !== "localhost") return route.abort();
    // Serve the deterministic dense POI fixture in place of the git-ignored
    // deploy artifact, so cluster density is identical on every platform.
    if (url.pathname.endsWith("/data/runtime_poi.json")) {
      return route.fulfill({ status: 200, contentType: "application/json; charset=utf-8", body: RUNTIME_POI_FIXTURE });
    }
    return route.continue();
  });
  // `load` (not domcontentloaded): boot()'s POI fetch/render runs after load, and the
  // cluster count is what these tests act on, so wait for the whole page to settle.
  await page.goto(`http://127.0.0.1:${port}/?haloRegressionTest=1&k12opt=thin`, { waitUntil: "load", timeout: 60000 });
  await page.waitForFunction(() => Boolean(window.__HALO_REGRESSION__ && window.__K12_THIN__));
  // Drive to the harness's deterministic dense-cluster view (zoom 14) so the
  // cluster population does not depend on the default fit, which varies with the
  // laid-out map size across platforms/headless.
  await page.waitForFunction(() => { try { const v = window.__HALO_REGRESSION__.mapView(); return v && isFinite(v.lat); } catch { return false; } });
  await page.evaluate(() => window.__HALO_REGRESSION__.setZoom(14));
  // POI clusters rendered (the workload `thin` optimises). On timeout, surface a
  // diagnostic (counts + any page error) so a CI-only failure is self-explaining.
  try {
    await page.waitForFunction(() => document.querySelectorAll(".poi-cluster-icon").length > 5);
  } catch (e) {
    const diag = await page.evaluate(() => ({
      clusterIcons: document.querySelectorAll(".poi-cluster-icon").length,
      markerIcons: document.querySelectorAll(".leaflet-marker-icon").length,
      canvases: document.querySelectorAll("#map canvas").length,
      zoom: (() => { try { return window.__HALO_REGRESSION__.mapView().zoom; } catch { return null; } })(),
    })).catch(() => ({}));
    console.error(`[k12-thin] cluster readiness failed: ${JSON.stringify(diag)} pageErrors=${JSON.stringify(pageErrors.slice(0, 5))}`);
    throw e;
  }
  page.context_ = context;
  return page;
}
const close = (page) => page.context_.close();

// Signature of the rendered clusters: sorted {rounded screen pos, count text}.
const clusterSignature = (page) =>
  page.evaluate(() =>
    [...document.querySelectorAll(".poi-cluster-icon")]
      .map((el) => {
        const r = el.getBoundingClientRect();
        return `${Math.round(r.left)},${Math.round(r.top)}:${(el.textContent || "").trim()}`;
      })
      .sort()
      .join("|")
  );
const visibleClusterCount = (page) =>
  page.evaluate(() => [...document.querySelectorAll(".poi-cluster-icon")].filter((el) => getComputedStyle(el).display !== "none").length);
const thinActive = (page) => page.evaluate(() => window.__K12_THIN__.active());
// A point on the map background away from any marker/cluster (upper-left quadrant).
async function mapDragPoint(page) {
  const box = await page.evaluate(() => { const m = document.getElementById("map").getBoundingClientRect(); return { x: m.left, y: m.top, w: m.width, h: m.height }; });
  return { x: box.x + box.w * 0.2, y: box.y + box.h * 0.25 };
}

test("thin: a user map DRAG hides cluster icons during the drag and restores them after", async () => {
  const page = await newPage();
  try {
    const originalView = await page.evaluate(() => window.__HALO_REGRESSION__.mapView());
    const before = await clusterSignature(page);
    const beforeCount = await visibleClusterCount(page);
    assert.ok(beforeCount > 5, "clusters present before");
    const p = await mapDragPoint(page);
    await page.mouse.move(p.x, p.y); await page.mouse.down();
    await page.mouse.move(p.x + 40, p.y + 30, { steps: 3 });
    await page.mouse.move(p.x + 90, p.y + 60, { steps: 4 });
    // DURING the drag: thin active and cluster icons not displayed.
    assert.equal(await thinActive(page), true, "thin active during drag");
    assert.equal(await visibleClusterCount(page), 0, "cluster icons hidden during drag");
    await page.mouse.up();
    await page.waitForFunction(() => window.__K12_THIN__.active() === false);
    assert.equal(await thinActive(page), false, "thin cleared after drag");
    assert.ok((await visibleClusterCount(page)) > 5, "clusters visible again after drag");
    // the container must not be left in either transient class
    assert.equal(await page.evaluate(() => { const c = document.getElementById("map"); return c.classList.contains("k12-panning"); }), false);
    // Identity/content proof: the drag moved the map, so screen positions are not
    // directly comparable to `before` until the view is put back exactly where it
    // started. Once recentred, the deterministic pixel-grid clustering must
    // reproduce the identical {screen-pos:count-text} signature — not just a count.
    await page.evaluate(({ lat, lon, zoom }) => window.__HALO_REGRESSION__.setMapView(lat, lon, zoom), originalView);
    await page.waitForFunction((n) => document.querySelectorAll(".poi-cluster-icon").length >= n, Math.min(beforeCount, 5));
    const after = await clusterSignature(page);
    assert.equal(after, before, "cluster identity/content/placement restored exactly at the original view");
  } finally { await close(page); }
});

